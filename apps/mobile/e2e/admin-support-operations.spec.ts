async function signIn(page: Page, path: string, role: 'dev-support' | 'dev-operator' = 'dev-support') {
  await page.goto(admin + path)
  await page.locator('input[autocomplete=username]').fill(role)
  await page.locator('input[autocomplete=current-password]').fill(role === 'dev-support' ? devPassword() : process.env.DEV_OPERATOR_PASSWORD!)
  await page.locator('form').getByRole('button', { name: '登录' }).click()
  await expect(page).toHaveURL(url => url.pathname === path)
}

async function downloadedText(download: Download) {
  const stream = await download.createReadStream()
  if (!stream) throw new Error('下载失败：浏览器没有生成文件')
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  return Buffer.concat(chunks).toString('utf8').trim()
}

