test('旧数字用户名与另一个用户的绑定号码重合时两者均可查询，结果均打码', async ({ page, request }) => {
  const phone = randomPhone()
  await signUpByApi(request, phone)
  const legacyId = randomUUID()
  // 旧数字登录名是历史数据，今天的开户页面不会生成。仅在隔离测试库创建只读查询对象。
  psql(`INSERT INTO identity_user(id, login_name, display_name, password_hash, default_organization_id)
        SELECT '${legacyId}', '${phone}', '旧用户名联调', '!', default_organization_id
        FROM identity_user WHERE mobile='${phone}'`)
  try {
    await signIn(page, '/lookup/users')
    await page.getByPlaceholder('手机号 / 账号 ID / 登录名 / 显示名').fill(phone)
    await page.getByTestId('user-lookup-search').click()
    const rows = page.locator('.el-table__row')
    await expect(rows).toHaveCount(2)
    const legacy = rows.filter({ hasText: '旧用户名联调' })
    await expect(legacy).toContainText(mask(phone))
    await expect(legacy).not.toContainText(phone)
    await legacy.getByRole('button').click()
    await expect(page.getByTestId('user-lookup-basics')).toContainText(legacyId)
    await expect(page.getByTestId('user-lookup-basics')).not.toContainText(phone)
  } finally {
    psql(`DELETE FROM identity_user WHERE id='${legacyId}' AND login_name='${phone}'`)
  }
})

