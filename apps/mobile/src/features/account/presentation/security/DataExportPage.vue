          <text class="data__sub">点开查看，敏感信息打码显示</text>
        </view>
        <button
          v-for="section in stored"
          :key="section.code"
          class="data__row"
          :data-testid="`data-section-${section.code.toLowerCase()}`"
          @click="emit('open', section.code)"
        >
          <view class="data__row-copy">
            <text class="data__row-title">{{ section.title }}</text>
            <text class="data__row-sub">{{ section.description }}</text>
          </view>
          <text v-if="section.count !== null" class="data__row-value">{{ section.count }} {{ section.code === 'PARTICIPANTS' ? '人' : section.code === 'ADDRESSES' ? '个' : section.code === 'ORDERS' ? '笔' : '家' }}</text>
          <LineIcon :d="CHEVRON" :size="14" color="#91a0b4" :stroke-width="2" />
        </button>
      </view>

      <view class="data__card data__records">
        <text class="data__title">导出记录</text>
        <view v-if="!latest" class="data__empty">
          <LineIcon :d="INFO" :size="18" color="#738096" :stroke-width="1.8" />
          <text class="data__empty-text">还没有导出记录，申请后在这里看进度和下载</text>
        </view>
        <template v-else>
          <view class="data__record" data-testid="data-record">
            <view class="data__record-icon"><LineIcon :d="FILE" :size="20" color="#1d63c4" :stroke-width="1.8" /></view>
            <view class="data__row-copy">
              <text class="data__record-title">个人信息副本</text>
              <text class="data__row-sub">{{ recordSub }}</text>
            </view>
            <text v-if="latest.status === 'PENDING'" class="data__tag" data-testid="data-record-making">生成中</text>
            <button v-else-if="latest.status === 'READY'" class="data__download" data-testid="data-download" aria-label="下载个人信息副本" @click="download">下载</button>
          </view>
          <view :class="['data__record-note', { 'data__record-note--ok': linkNote }]">
            <LineIcon v-if="linkNote" :d="CHECK" :size="14" color="#11804a" :stroke-width="2.4" />
            <text>{{ recordNote }}</text>
          </view>
        </template>
        <text class="data__fine">文件经受控链接下载，不显示存储地址；导出会留下记录</text>
      </view>
      <view v-if="error" class="data__error" role="alert">
        <text>{{ error }}</text>
        <button @click="load">重新加载</button>
      </view>
    </view>

    <view class="data__bar">
      <button
        :class="['data__apply', { 'data__apply--off': making }]"
        :disabled="making || !overview"
        role="button"
        :aria-disabled="making || !overview ? 'true' : 'false'"
        data-testid="data-apply"
        @click="openSheet"
      >{{ !overview ? (error ? '暂时无法申请' : '正在读取导出信息') : making ? '副本生成中' : latest?.status === 'READY' ? '重新申请导出' : '申请导出' }}</button>
    </view>

    <template v-if="sheetOpen && overview">
      <view class="data__mask" @click="sheetOpen = false" />
      <view class="data__sheet" role="dialog" aria-label="申请导出个人信息" data-testid="data-sheet">
        <view class="data__sheet-head">
          <text class="data__sheet-title">申请导出个人信息</text>
          <text class="data__sub">选择要导出的内容，并验证手机号 {{ overview.maskedPhone }}</text>
        </view>
        <view class="data__scope">
          <view
            v-for="section in overview.sections"
            :key="section.code"
            class="data__scope-item"
            role="checkbox"
            :aria-checked="off.includes(section.code) ? 'false' : 'true'"
            :data-testid="`data-scope-${section.code.toLowerCase()}`"
            @click="toggle(section.code)"
          >
            <view :class="['data__tick', { 'data__tick--on': !off.includes(section.code) }]">
              <LineIcon v-if="!off.includes(section.code)" :d="CHECK" :size="12" color="#ffffff" :stroke-width="3.2" />
            </view>
            <text>{{ section.title }}</text>
          </view>
        </view>
        <SmsCodeField v-model="code" label="验证码" test-id="data-export" :send="sendCode" />
        <text class="data__fine">提交后服务端生成副本，通常 1 分钟内完成，本页会自动刷新。副本含敏感信息，请妥善保管。</text>
        <view class="data__sheet-actions">
          <button class="data__ghost" @click="sheetOpen = false">取消</button>
          <button :class="['data__primary', { 'data__primary--off': !canSubmit }]" :disabled="!canSubmit" data-testid="data-submit" @click="submit">提交申请</button>
        </view>
      </view>
    </template>
  </view>
</template>

