<script setup lang="ts">
import { computed, onMounted, onUnmounted, ref } from 'vue'

import AppPageHeader from '@/shared/ui/AppPageHeader.vue'
import LineIcon from '@/shared/ui/LineIcon.vue'
import { toBeijingParts } from '@/shared/time/beijing-time'

import { downloadExport } from '../../application/export-download'
import { identityAccountApi } from '../../data/identity-account-api-client'
import type { DataExport, DataExportOverview, DataSectionCode } from '../../domain/identity-account'
import { formatBytes, isSmsCode } from '../../domain/identity-account'
import SmsCodeField from '../shared/SmsCodeField.vue'

// 个人信息查看与导出 (board SetData, 390 wide): what the account is, what the platform keeps (each row
// opens the page that shows it), and a copy to download: chosen sections, the current number
// verified, generated by the server, one five-minute link per download.
const props = defineProps<{
  accessToken: string
  profile: { displayName: string; maskedPhone: string | null; cityName: string | null; identityText: string }
}>()
const emit = defineEmits<{ back: []; open: [code: DataSectionCode]; phone: []; unauthorized: [] }>()

const CHEVRON = 'M9 5l7 7-7 7'
const CHECK = 'M5 12l5 5 9-10'
const INFO = 'M12 3a9 9 0 1 0 0 18a9 9 0 1 0 0-18zM12 11v5M12 7.5h.01'
const FILE = 'M6 3h9l4 4v14H6zM14 3v5h5M9 13h7M9 17h5'

const overview = ref<DataExportOverview | null>(null)
const error = ref('')
const sheetOpen = ref(false)
const off = ref<DataSectionCode[]>([])
const code = ref('')
const submitting = ref(false)
const linkNote = ref('')
let poll: ReturnType<typeof setInterval> | null = null

const stored = computed(() => (overview.value?.sections ?? []).filter((section) => section.code !== 'ACCOUNT'))
const latest = computed<DataExport | null>(() => overview.value?.exports[0] ?? null)
const making = computed(() => latest.value?.status === 'PENDING')
const picked = computed(() => (overview.value?.sections ?? []).filter((section) => !off.value.includes(section.code)))
const canSubmit = computed(() => picked.value.length > 0 && isSmsCode(code.value) && !submitting.value)

function day(iso: string | null): string {
  if (!iso) return ''
  const parts = toBeijingParts(new Date(iso))
  return `${String(parts.month).padStart(2, '0')}/${String(parts.day).padStart(2, '0')}`
}

const recordSub = computed(() => {
  const record = latest.value
  if (!record) return ''
  const count = `${record.sections.length} 项内容`
  if (record.status === 'PENDING') return `${day(record.requestedAt)} 提交 · ${count}`
  if (record.status === 'READY') return `${day(record.readyAt)} 已生成 · ${count} · ${formatBytes(record.sizeBytes)}`
  if (record.status === 'EXPIRED') return `${day(record.requestedAt)} 提交 · 已过期`
  return `${day(record.requestedAt)} 提交 · 生成失败`
})

const recordNote = computed(() => {
  const record = latest.value
  if (!record) return ''
  if (linkNote.value) return linkNote.value
  if (record.status === 'PENDING') return '服务端正在生成，通常 1 分钟内完成，本页会自动刷新'
  if (record.status === 'READY') return `副本保留到 ${day(record.expiresAt)}，过期后需要重新申请`
  if (record.status === 'EXPIRED') return '副本已过期删除，需要时重新申请'
  return '没能生成副本，可以重新申请'
})

async function load(): Promise<void> {
  try {
    overview.value = await identityAccountApi.readDataExports(props.accessToken)
    error.value = ''
    if (making.value && !poll) poll = setInterval(() => void load(), 5000)
    if (!making.value && poll) {
      clearInterval(poll)
      poll = null
    }
  } catch (reason) {
    if ((reason as { status?: number }).status === 401) emit('unauthorized')
    error.value = reason instanceof Error ? reason.message : '读取失败，请重试'
  }
}

function toggle(sectionCode: DataSectionCode): void {
  off.value = off.value.includes(sectionCode) ? off.value.filter((item) => item !== sectionCode) : [...off.value, sectionCode]
}

async function sendCode(): Promise<number> {
  try {
    return (await identityAccountApi.sendAccountCode(props.accessToken, 'EXPORT')).resendAfterSeconds
  } catch (reason) {
    uni.showToast({ title: reason instanceof Error ? reason.message : '验证码发送失败', icon: 'none' })
    throw reason
  }
}

function openSheet(): void {
  if (!overview.value?.maskedPhone) {
    uni.showModal({
      title: '先绑定手机号',
      content: '导出个人信息要验证手机号，请先绑定手机号',
      confirmText: '去绑定',
      cancelText: '取消',
      confirmColor: '#ff6a00',
      success: (result) => { if (result.confirm) emit('phone') },
    })
    return
  }
  off.value = []
  code.value = ''
  sheetOpen.value = true
}

async function submit(): Promise<void> {
  if (!canSubmit.value) return
  submitting.value = true
  try {
    await identityAccountApi.requestDataExport(props.accessToken, picked.value.map((section) => section.code), code.value)
    sheetOpen.value = false
    linkNote.value = ''
    await load()
  } catch (reason) {
    uni.showToast({ title: reason instanceof Error ? reason.message : '提交失败，请重试', icon: 'none' })
  } finally {
    submitting.value = false
  }
}

async function download(): Promise<void> {
  const record = latest.value
  if (!record) return
  try {
    const intent = await identityAccountApi.createDownload(props.accessToken, record.exportId)
    linkNote.value = await downloadExport(intent.downloadUrl, intent.fileName)
  } catch (reason) {
    uni.showToast({ title: reason instanceof Error ? reason.message : '下载失败，请重试', icon: 'none' })
    void load()
  }
}

onMounted(load)
onUnmounted(() => {
  if (poll) clearInterval(poll)
})
</script>

<template>
  <view class="data" data-testid="data-page">
    <AppPageHeader title="个人信息查看与导出" test-id="data" @back="emit('back')" />
    <view class="data__body">
      <view class="data__card data__profile">
        <text class="data__title">账号信息</text>
        <view class="data__grid">
          <text class="data__key">姓名</text><text>{{ profile.displayName }}</text>
          <text class="data__key">手机号</text><text data-testid="data-phone">{{ profile.maskedPhone || '未绑定' }}</text>
          <text class="data__key">常用城市</text><text>{{ profile.cityName || '未设置' }}</text>
          <text class="data__key">企业身份</text><text>{{ profile.identityText }}</text>
        </view>
      </view>

      <view class="data__card data__stored">
        <view class="data__stored-head">
